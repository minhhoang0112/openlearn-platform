import assert from 'node:assert/strict';
import ts from 'typescript';
import fs from 'node:fs/promises';
// This module has type-only dependencies; transform erases them for Node.
const code = ts.transpileModule(await fs.readFile(new URL('../src/utils/library.ts', import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext } }).outputText;
const { parseImport, saveSet, readLibrary } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const store = new Map();
globalThis.localStorage = { getItem: key => store.get(key) ?? null, setItem: (key, value) => store.set(key, value) };
const course = { id: 'hsk-1', title: 'HSK I', language: 'zh', level: 'HSK 1' };
const chinese = parseImport('term,definition,phonetic,example\r\n你好,"xin chào, chào bạn",nǐ hǎo,"你好！"\r\n谢谢,cảm ơn,xièxie,谢谢你', 'test.csv', course);
assert.equal(chinese.words.length, 2);
assert.equal(chinese.words[0].definition, 'xin chào, chào bạn');
assert.equal(chinese.words[0].language, 'zh-CN');
assert.equal(chinese.id, 'hsk-1');
assert.equal(parseImport('term\tdefinition\n本\tsách', 'test.tsv').words[0].term, '本');
assert.equal(parseImport('term,definition\nhello,"say ""hello""\non a new line"', 'test.csv').words[0].definition, 'say "hello"\non a new line');
assert.equal(parseImport(JSON.stringify({ title: 'My set', words: [{ term: 'hello', definition: 'xin chào' }] }), 'test.json').title, 'My set');
assert.equal(parseImport(JSON.stringify({ language: 'ja', words: [{ term: '本', definition: 'sách' }] }), 'test.json').words[0].language, 'ja-JP');
assert.throws(() => parseImport('[]', 'empty.json'));
assert.throws(() => parseImport('[{"term":"hello"}]', 'invalid.json'));
assert.throws(() => parseImport('term,definition\nhello,"unclosed', 'broken.csv'));
saveSet(chinese);
assert.equal(readLibrary().length, 1);
saveSet({ ...chinese, title: 'Updated' });
assert.equal(readLibrary().length, 1);
assert.equal(readLibrary()[0].title, 'Updated');
store.set('openquiz.library.v1', '{bad-json');
assert.deepEqual(readLibrary(), []);
console.log('PASS: multilingual CSV/TSV/JSON, quoted fields, validation, persistence, and corrupt storage.');
